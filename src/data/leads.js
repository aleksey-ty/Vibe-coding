export function getDashboardStats(items) {
  return {
    newCount: items.filter((lead) => lead.status === 'new').length,
    hotCount: items.filter((lead) => lead.heat === 'hot').length,
    processedCount: items.filter((lead) => lead.status === 'processed').length,
  }
}

const heatRank = { hot: 3, warm: 2, cold: 1 }
const statusRank = { new: 3, hot: 2, processed: 1 }

export function getLeadPriority(lead) {
  const heat = heatRank[lead.heat] ?? 0
  const status = statusRank[lead.status] ?? 0
  return heat * 10 + status
}

export function sortLeadsByPriority(items) {
  return [...items].sort((a, b) => {
    const byPriority = getLeadPriority(b) - getLeadPriority(a)
    if (byPriority !== 0) return byPriority
    if (b.value !== a.value) return b.value - a.value
    return b.createdAt.localeCompare(a.createdAt)
  })
}

// Пороги приоритета по потенциальной сумме.
const VALUE_COLD_MAX = 30000
const VALUE_WARM_MAX = 100000

// heat — это ПРИОРИТЕТ заявки по потенциальной сумме.
// Он не связан со статусом обработки (status) и не меняется при workflow.
export function getHeatByValue(value) {
  // Сумма не указана — считаем заявку «тёплой».
  if (value === null || value === undefined || value === '') return 'warm'

  const amount = Number(value)

  // Некорректное значение не должно ломать создание заявки.
  if (!Number.isFinite(amount)) return 'warm'

  if (amount < VALUE_COLD_MAX) return 'cold'
  if (amount < VALUE_WARM_MAX) return 'warm'

  return 'hot'
}

