export function getDashboardStats(items) {
  return {
    newCount: items.filter((lead) => lead.status === 'new').length,
    hotCount: items.filter((lead) => lead.heat === 'hot').length,
    processedCount: items.filter((lead) => lead.status === 'processed').length,
  }
}

// Сколько заявок уже разобрал AI: используется в списке заявок и в настройках.
export function getAnalysisStats(items) {
  const analyzed = items.filter((lead) => lead.aiAnalysis).length

  return {
    analyzed,
    pending: items.length - analyzed,
    totalValue: items.reduce((sum, lead) => sum + (Number(lead.value) || 0), 0),
  }
}

const heatRank = { hot: 3, warm: 2, cold: 1 }
const statusRank = { new: 3, hot: 2, processed: 1 }

export function getLeadPriority(lead) {
  const heat = heatRank[lead.heat] ?? 0
  const status = statusRank[lead.status] ?? 0
  return heat * 10 + status
}

export function sortLeadsByPriority(items) {
  return [...items].sort((a, b) => {
    const byPriority = getLeadPriority(b) - getLeadPriority(a)
    if (byPriority !== 0) return byPriority
    if (b.value !== a.value) return b.value - a.value
    return b.createdAt.localeCompare(a.createdAt)
  })
}

// Пороги приоритета по потенциальной сумме.
const VALUE_COLD_MAX = 30000
const VALUE_WARM_MAX = 100000

// heat — это ПРИОРИТЕТ заявки по потенциальной сумме.
// Он не связан со статусом обработки (status) и не меняется при workflow.
export function getHeatByValue(value) {
  // Сумма не указана — считаем заявку «тёплой».
  if (value === null || value === undefined || value === '') return 'warm'

  const amount = Number(value)

  // Некорректное значение не должно ломать создание заявки.
  if (!Number.isFinite(amount)) return 'warm'

  if (amount < VALUE_COLD_MAX) return 'cold'
  if (amount < VALUE_WARM_MAX) return 'warm'

  return 'hot'
}

// Стадии демонстрационной воронки продаж. Порядок стадий задаёт порядок колонок.
export const pipelineStages = [
  { id: 'new', title: 'Новые', hint: 'AI ещё не разобрал заявку' },
  { id: 'qualification', title: 'Квалификация', hint: 'Нужны уточняющие вопросы клиенту' },
  { id: 'in_progress', title: 'В работе', hint: 'Менеджер ведёт заявку' },
  { id: 'discussion', title: 'Обсуждение', hint: 'Обсуждаем условия и старт работ' },
  { id: 'closed', title: 'Закрыто', hint: 'Заявка обработана' },
]

// Стадия выводится из статуса заявки и её AI-анализа, поэтому одна заявка
// всегда попадает ровно на одну стадию. Это demo-модель воронки: отдельного
// хранилища стадий нет, всё считается из существующего списка заявок.
export function getPipelineStageId(lead) {
  if (lead.status === 'processed') return 'closed'

  // Статус «В работе» (hot): AI-hot лиды уже обсуждают условия, остальные в работе.
  if (lead.status === 'hot') {
    return lead.aiAnalysis?.priority === 'hot' ? 'discussion' : 'in_progress'
  }

  // Статус «Новая»: пока нет AI-анализа — заявку ещё не разбирали.
  if (!lead.aiAnalysis) return 'new'

  return 'qualification'
}

const aiPriorityRank = { hot: 3, warm: 2, cold: 1 }

// Стадии вместе с заявками: количество и потенциальная сумма считаются
// из данных, а не задаются вручную.
export function getPipeline(items) {
  const stages = pipelineStages.map((stage) => ({ ...stage, leads: [], total: 0 }))
  const stagesById = new Map(stages.map((stage) => [stage.id, stage]))

  for (const lead of items) {
    const stage = stagesById.get(getPipelineStageId(lead))
    if (!stage) continue

    stage.leads.push(lead)
    stage.total += Number(lead.value) || 0
  }

  for (const stage of stages) {
    stage.leads.sort((a, b) => {
      const byAi = (aiPriorityRank[b.aiAnalysis?.priority] ?? 0) - (aiPriorityRank[a.aiAnalysis?.priority] ?? 0)
      if (byAi !== 0) return byAi
      return (Number(b.value) || 0) - (Number(a.value) || 0)
    })
    stage.count = stage.leads.length
  }

  return stages
}